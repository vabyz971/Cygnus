//! Photo scenario without a window (docs/decisions/0027, variant without
//! filter while filters wait for B10): imports of a 16-bit PNG and an 8-bit
//! JPEG generated by `photo/io` (example `fixtures`), adjustments with a
//! mask, an isolated group with a Multiply layer and a clipped
//! adjustment, a JPEG in Screen at 60 %, undo and redo, then a change that
//! clears the redo stack.

#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::path::{Path, PathBuf};
use std::process::Command;

use cygnus_commands::{CommandBus, Source};
use cygnus_photo_core::resolve::{Resolvers, resolve_and_execute};
use cygnus_photo_core::script::Script;
use cygnus_photo_core::{Document, PhotoCommand};
use cygnus_photo_io::FileImporter;
use cygnus_photo_render::{ExportBits, Image, gpu};

fn scenario_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/scenario")
}

fn script() -> Script {
    let text = std::fs::read_to_string(scenario_dir().join("scenario-photo.json")).unwrap();
    Script::parse(&text).unwrap()
}

/// Largest difference between adapters on one channel, and largest mean
/// difference (docs/decisions/0016), in 16-bit units.
const TOLERANCE_UNITS: u16 = 1;
const MEAN_UNITS_BOUND: f64 = 0.01;

#[test]
fn the_scenario_renders_like_its_golden_image() {
    let adapter = match gpu::open_headless() {
        Ok(gpu) => gpu.info.name.clone(),
        Err(error) => {
            let required = std::env::var("CYGNUS_REQUIRE_GPU").is_ok_and(|value| value == "1");
            assert!(!required, "GPU required but unavailable: {error}");
            println!("skipped, no GPU: {error}");
            return;
        }
    };
    let output = Path::new(env!("CARGO_TARGET_TMPDIR")).join("scenario-photo.png");
    let run = Command::new(env!("CARGO_BIN_EXE_cygnus"))
        .args(["render"])
        .arg(scenario_dir().join("scenario-photo.json"))
        .arg(&output)
        .args(["--bits", "16"])
        .output()
        .unwrap();
    assert!(
        run.status.success(),
        "cygnus render failed: {}",
        String::from_utf8_lossy(&run.stderr)
    );
    let actual = Image::read_png(&std::fs::read(&output).unwrap()).unwrap();
    assert_eq!(actual.bits, ExportBits::Sixteen);
    let reference = scenario_dir().join("scenario-photo.png");
    if std::env::var("CYGNUS_UPDATE_GOLDEN").is_ok_and(|value| value == "1") {
        assert!(
            adapter.contains("llvmpipe"),
            "golden images are made on lavapipe, not on {adapter}"
        );
        std::fs::copy(&output, &reference).unwrap();
        println!("scenario-photo: reference written");
        return;
    }
    let expected = Image::read_png(&std::fs::read(&reference).unwrap()).unwrap();
    assert_eq!(
        (expected.width, expected.height),
        (actual.width, actual.height)
    );
    let mut max = 0u16;
    let mut sum = 0u64;
    for (a, b) in expected.data.iter().zip(&actual.data) {
        let units = a.abs_diff(*b);
        max = max.max(units);
        sum += u64::from(units);
    }
    let mean = sum as f64 / expected.data.len() as f64;
    let line = format!("scenario-photo on {adapter}: max {max} units, mean {mean:.5}");
    println!("{line}");
    if std::env::var("GITHUB_ACTIONS").is_ok() {
        println!("::notice title=golden scenario-photo::{line}");
    }
    if max > TOLERANCE_UNITS || mean > MEAN_UNITS_BOUND {
        let failures = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../target/golden-failures");
        std::fs::create_dir_all(&failures).unwrap();
        std::fs::copy(&output, failures.join("scenario-photo-actual.png")).unwrap();
        panic!("{line}: beyond the tolerance of 0016");
    }
}

/// Runs the scenario through the single resolution path, returning the
/// bus and the document.
fn run_scenario() -> (CommandBus<PhotoCommand>, Document) {
    let importer = FileImporter::new(scenario_dir());
    let resolvers = Resolvers {
        import: Some(&importer),
        merge: None,
    };
    let mut bus = CommandBus::new();
    let mut document = Document::default();
    for command in script().commands {
        resolve_and_execute(&mut bus, &mut document, command, Source::Cli, &resolvers).unwrap();
    }
    (bus, document)
}

#[test]
fn undoing_everything_then_redoing_everything_gives_the_same_document() {
    let (mut bus, mut document) = run_scenario();
    assert_eq!(document.sources.len(), 2, "two embedded sources");
    // The redo stack was cleared by the last change.
    assert!(!bus.can_redo());
    let end = document.clone();
    let mut undone = 0;
    while bus.undo(&mut document, Source::User).unwrap() {
        undone += 1;
    }
    assert!(undone > 10, "{undone} entries undone");
    assert_eq!(document, Document::default());
    while bus.redo(&mut document, Source::User).unwrap() {}
    assert_eq!(document, end);
}

#[test]
fn the_history_keeps_the_paths_not_the_pixels() {
    let (bus, _) = run_scenario();
    // Both imports are listed under their public name. An entry undone then
    // redone keeps its name, but holds the internal command that redoes it
    // (the bus keeps the inverse of the inverse): only the first import,
    // never undone, still shows its path.
    let names: Vec<&str> = bus
        .entries()
        .map(|entry| entry.name)
        .filter(|name| *name == "source.import")
        .collect();
    assert_eq!(names.len(), 2);
    let first = bus
        .entries()
        .find(|entry| entry.name == "source.import")
        .unwrap();
    let PhotoCommand::SourceImport(params) = &first.command else {
        panic!("recorded {:?}", first.command);
    };
    assert_eq!(params.path, "../fixtures/paysage-16.png");
    // Serialized, an import is its public form: the path, no pixels.
    let json = serde_json::to_string(&first.command).unwrap();
    assert!(json.len() < 200, "{json}");
}
