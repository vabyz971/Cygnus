//! Assembly of the WGSL shaders.
//!
//! WGSL has no imports: each shader is the concatenation of a generated
//! prelude (constants shared with Rust), the common modules it uses
//! (`color.wgsl`, `blend.wgsl`) and its own source. The compute format is
//! substituted from [`crate::format`], with its packing functions, blend mode codes from
//! [`BlendMode`], so that Rust and WGSL cannot disagree.

use cygnus_photo_core::BlendMode;
use cygnus_photo_core::pixels::TILE_SIZE;

use crate::format::{
    COMPUTE_CODEC_WGSL, COMPUTE_FORMAT_WGSL, COMPUTE_SAMPLED_WGSL, SOURCE_CODEC_WGSL,
};

const COLOR: &str = include_str!("shaders/color.wgsl");
const BLEND: &str = include_str!("shaders/blend.wgsl");
const ADJUST: &str = include_str!("shaders/adjust.wgsl");
const COMPOSITE: &str = include_str!("shaders/composite.wgsl");
const EXPORT: &str = include_str!("shaders/export.wgsl");
const DISPLAY: &str = include_str!("shaders/display.wgsl");
const DOWNSAMPLE: &str = include_str!("shaders/downsample.wgsl");
const HISTOGRAM: &str = include_str!("shaders/histogram.wgsl");

/// Name of the WGSL constant holding the code of `mode`, such as
/// `BLEND_SOFT_LIGHT`.
pub fn blend_constant(mode: BlendMode) -> String {
    let mut name = String::from("BLEND");
    for c in format!("{mode:?}").chars() {
        if c.is_ascii_uppercase() {
            name.push('_');
        }
        name.push(c.to_ascii_uppercase());
    }
    name
}

fn prelude() -> String {
    let mut prelude = String::from("// Generated by photo/render/src/shaders.rs.\n");
    prelude.push_str(&format!("const TILE_SIZE: u32 = {TILE_SIZE}u;\n"));
    prelude.push_str(&format!(
        "const STACK_DEPTH: u32 = {}u;\n",
        crate::program::STACK_DEPTH
    ));
    for mode in BlendMode::ALL {
        prelude.push_str(&format!(
            "const {}: u32 = {}u;\n",
            blend_constant(mode),
            mode.code()
        ));
    }
    for (name, code) in crate::adjust::KINDS {
        prelude.push_str(&format!("const {name}: u32 = {code}u;\n"));
    }
    prelude
}

fn assemble(main: &str, modules: &[&str]) -> String {
    let mut source = prelude();
    source.push_str(COMPUTE_CODEC_WGSL);
    source.push_str(SOURCE_CODEC_WGSL);
    for module in modules {
        source.push_str(module);
    }
    source.push_str(main);
    source
        .replace("COMPUTE_FORMAT", COMPUTE_FORMAT_WGSL)
        .replace("COMPUTE_SAMPLED", COMPUTE_SAMPLED_WGSL)
}

/// Composite pass: composition program of each tile, reading the source
/// pools.
pub fn composite() -> String {
    assemble(COMPOSITE, &[COLOR, BLEND, ADJUST])
}

/// Export pass: compute format to 8- or 16-bit sRGB.
pub fn export() -> String {
    assemble(EXPORT, &[COLOR])
}

/// Downsample pass: pyramid level L from level L - 1.
pub fn downsample() -> String {
    assemble(DOWNSAMPLE, &[COLOR])
}

/// Histogram pass: counts of the composite tiles shown.
pub fn histogram() -> String {
    assemble(HISTOGRAM, &[COLOR])
}

/// Display pass: composite tiles to the screen.
pub fn display() -> String {
    assemble(DISPLAY, &[COLOR])
}

#[cfg(test)]
mod tests {
    use super::*;
    use wgpu::naga;

    fn validate(name: &str, source: &str) {
        let module = naga::front::wgsl::parse_str(source)
            .unwrap_or_else(|error| panic!("{name}: {}", error.emit_to_string(source)));
        naga::valid::Validator::new(
            naga::valid::ValidationFlags::all(),
            naga::valid::Capabilities::empty(),
        )
        .validate(&module)
        .unwrap_or_else(|error| panic!("{name}: {error:?}"));
    }

    #[test]
    fn every_shader_is_valid_wgsl() {
        validate("composite", &composite());
        validate("export", &export());
        validate("display", &display());
        validate("downsample", &downsample());
        validate("histogram", &histogram());
    }

    #[test]
    fn blend_constants_follow_rust_names() {
        assert_eq!(blend_constant(BlendMode::Normal), "BLEND_NORMAL");
        assert_eq!(blend_constant(BlendMode::SoftLight), "BLEND_SOFT_LIGHT");
    }

    #[test]
    fn every_mode_has_a_case_in_the_blend_module() {
        for mode in BlendMode::ALL {
            let case = format!("case {}:", blend_constant(mode));
            assert!(BLEND.contains(&case), "blend.wgsl lacks `{case}`");
        }
    }

    #[test]
    fn blend_formulas_live_only_in_the_blend_module() {
        // The normal formula and the blend function are defined once.
        for (name, source) in [
            ("color", COLOR),
            ("adjust", ADJUST),
            ("composite", COMPOSITE),
            ("export", EXPORT),
            ("display", DISPLAY),
            ("downsample", DOWNSAMPLE),
        ] {
            assert!(
                !source.contains("fn blend"),
                "{name}.wgsl defines a blend function"
            );
        }
        // Color conversions are defined once too.
        for (name, source) in [
            ("blend", BLEND),
            ("adjust", ADJUST),
            ("composite", COMPOSITE),
            ("export", EXPORT),
            ("display", DISPLAY),
            ("downsample", DOWNSAMPLE),
        ] {
            assert!(
                !source.contains("fn srgb_to_linear"),
                "{name}.wgsl converts colors"
            );
            assert!(
                !source.contains("fn linear_to_srgb"),
                "{name}.wgsl converts colors"
            );
        }
    }
}
